def draw_char_5x7(x: int, y: int, char: str, color: int, draw_func) -> None:
    """Draw a 5x7 character at position (x, y)."""
    if char not in FONT_5X7:
        return
    bitmap = FONT_5X7[char]
    for row in range(7):
        for col in range(5):
            if bitmap[row] & (1 << (4 - col)):
                draw_func(x + col, y + row, 1, 1, color)


def draw_text_5x7(x: int, y: int, text: str, color: int, draw_func) -> None:
    """Draw 5x7 text at position (x, y)."""
    for i, ch in enumerate(text):
        draw_char_5x7(x + i * 6, y, ch, color, draw_func)


def draw_char_8x10(x: int, y: int, char: str, color: int, draw_func) -> None:
    """Draw an 8x10 character at position (x, y)."""
    if char not in FONT_8X10:
        return
    bitmap = FONT_8X10[char]
    for row in range(10):
        for col in range(8):
            if bitmap[row] & (1 << (7 - col)):
                draw_func(x + col, y + row, 1, 1, color)


def draw_text_8x10(x: int, y: int, text: str, color: int, draw_func) -> None:
    """Draw 8x10 text at position (x, y)."""
    for i, ch in enumerate(text):
        draw_char_8x10(x + i * 9, y, ch, color, draw_func)
